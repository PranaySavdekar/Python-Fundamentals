# Problem5: Count the number of uppercase and lowercase letters in a string.
# ===========================================================================================================================
string= "I aM eAting a SaNdwIch "
count_upper=0
count_lower=0
for char in string:
    if char.isupper():
        count_upper+=1
    elif char.islower():
        count_lower+=1
print(count_upper)
print(count_lower)
