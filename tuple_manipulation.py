# ==============================================================================
# Problem 1: Find the sum of all elements in a tuple using a loop
# ==============================================================================

nums = (1,2,3,4,5)
total = 0

for num in nums:
    total += num

print(total)

# ==============================================================================
# Problem 2: Count how many even numbers are in a tuple
# ==============================================================================
nums = (10, 15, 20, 25, 30)
count = 0

for num in nums:
    if num % 2 == 0:
        count += 1

print(count)


# ==============================================================================
# Problem 3: Multiply all elements in a tuple
# ==============================================================================

nums = (2, 3, 4)
result = 1

for num in nums:
    result *= num

print(result)


# ==============================================================================
# Problem 4: Add corresponding elements from two tuples
# ==============================================================================

nums1 = (1, 2, 3)
nums2 = (4, 5, 6)
result = ()

for i in range(len(nums1)):
    result += (nums1[i] + nums2[i],)

print(result)

# ==============================================================================
# Problem 5: Find all elements greater than 50 in a tuple
# ==============================================================================

nums = (20, 55, 60, 30, 75)
result = ()

for num in nums:
    if num > 50:
        result += (num,)

print(result)

# ==============================================================================
# Problem 6: Remove duplicates from a tuple
# ==============================================================================
nums=(1,2,4,3,34,22,4,4,1,22)
result = []

for num in nums:
    if num not in result:
        result.append(num)

result = tuple(result)

print(result)

# ===========================================================================================================================
# Problem 7: Sort the elements of a tuple in ascending order.
# ===========================================================================================================================

nums = (5, 2, 8, 1, 9, 3)

result = list(nums)
result.sort()
result = tuple(result)

print(result)

