# Problem 6: Find duplicate elements in a list
# ===========================================================================================================================
nums = [1,2,2,3,4,4,5,5,5]
duplicates = []
for num in nums:
    if nums.count(num) > 1 and num not in duplicates:
        duplicates.append(num)
print("Duplicates:", duplicates)

