# ==============================================================================
# Problem 1: Convert list to set and remove duplicates
# Input: [1, 2, 2, 3, 4, 4, 5] Output: {1, 2, 3, 4, 5}
# ==============================================================================

nums = [1, 2, 2, 3, 4, 4, 5]
result = set(nums)

print(result)

# ==============================================================================
# Problem 2: Print all elements of a set using a loop
# ==============================================================================
nums = {10, 20, 30}

for num in nums:
    print(num)


# ==============================================================================
# Problem 3: Copy one set into another
# ==============================================================================

set1 = {10, 20}
set2 = set1.copy()

print(set2)


# ==============================================================================
# Problem 4: Find the union of two sets
# ==============================================================================

set1 = {1, 2, 3}
set2 = {3, 4, 5}

result = set1 | set2

print(result)



# ==============================================================================
# Problem 5: Find the intersection of two sets
# ==============================================================================

set1 = {1, 2, 3}
set2 = {2, 3, 4}

result = set1 & set2

print(result)



# ==============================================================================
# Problem 6: Find the difference between two sets
# ==============================================================================

set1 = {1, 2, 3}
set2 = {2, 3, 4}

result = set1 - set2

print(result)

# ==============================================================================
# Problem 7: Check if set is subset and superset
# ==============================================================================

set1 = {1, 2}
set2 = {1, 2, 3, 4}

print(set1.issubset(set2))
print(set2.issuperset(set1))



# ==============================================================================
# Problem 8: Convert string to set and remove vowels
# ==============================================================================

string = "datascience"
vowels = "aeiou"

result = {char for char in string if char not in vowels}

print(result)



# ==============================================================================
# Problem 9: Check if an element exists in a set

# ==============================================================================

nums = {10, 20, 30, 40}
print(30 in nums)


# ==============================================================================
# Problem 10: Remove an element from a set using discard()
# ==============================================================================

nums = {10, 20, 30, 40}
nums.discard(30)

print(nums)


# ==============================================================================
# Problem 11: Find the symmetric difference between two sets
# Input: {1, 2, 3} and {3, 4, 5}
# Output: {1, 2, 4, 5}
# ==============================================================================

set1 = {1, 2, 3}
set2 = {3, 4, 5}

result = set1 ^ set2

print(result)

